"""Subset the existing local fonts; requires `pip install fonttools[woff]`.

The complete DM Serif Display faces remain the fallback for any new characters
when the heading changes. No font service is contacted by the storefront.
"""
import hashlib
import json
from io import BytesIO
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[2]
faces = [
    ("normal", "dm-serif-display-latin.woff2", "Tu mezcla."),
    ("italic", "dm-serif-display-latin-italic.woff2", "Tus reglas."),
]
manifest = []
css = ["/* Generated by scripts/media/prepare-hero-fonts.py. */"]
for style, source, text in faces:
    font = TTFont(root / "public/fonts" / source)
    options = subset.Options()
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(text=text)
    subsetter.subset(font)
    # Stable timestamps make repeated runs produce the same content hash.
    font.recalcTimestamp = False
    output = BytesIO()
    font.save(output)
    data = output.getvalue()
    digest = hashlib.sha256(data).hexdigest()[:12]
    url = f"/fonts/hero-{style}-{digest}.woff2"
    (root / "public" / url.lstrip("/")).write_bytes(data)
    manifest.append({"url": url, "style": style, "bytes": len(data)})
    unicode_range = ",".join(f"U+{ord(char):X}" for char in sorted(set(text)))
    css.append(
        f"@font-face {{ font-family: 'DM Serif Hero'; src: url('{url}') format('woff2'); "
        f"font-weight: 400; font-style: {style}; font-display: swap; unicode-range: {unicode_range}; }}"
    )
    print(f"{source}: {len(data)} bytes for the mobile heading")

(root / "src/config/hero-fonts.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
(root / "src/config/hero-fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")
